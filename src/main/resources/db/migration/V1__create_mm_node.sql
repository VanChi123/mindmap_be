-- Một bảng tự tham chiếu cho mọi ô trên sơ đồ.
-- parent_id NULL  = đối tượng gốc (Tôi, Vợ, Bố, Mẹ, Con chó...)
-- parent_id có giá trị = chủ đề / mục nhỏ nằm trong ô cha.
CREATE TABLE mm_node (
  id         NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  parent_id  NUMBER(19),
  title      VARCHAR2(200 CHAR) NOT NULL,
  content    CLOB,
  pos_x      NUMBER(10,2) DEFAULT 0 NOT NULL,
  pos_y      NUMBER(10,2) DEFAULT 0 NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_mm_node_parent FOREIGN KEY (parent_id)
    REFERENCES mm_node (id) ON DELETE CASCADE
);

CREATE INDEX ix_mm_node_parent ON mm_node (parent_id);
